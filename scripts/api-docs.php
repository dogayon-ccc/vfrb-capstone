<?php

// Regenerates docs/API.md: `php scripts/api-docs.php`. Fields are read from controller source, so no database is touched.

require __DIR__.'/../vendor/autoload.php';
$app = require __DIR__.'/../bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

const CORE = [
    'POST /api/login', 'POST /api/admin/login', 'POST /api/logout', 'GET /api/user', 'POST /api/password/forgot', 'POST /api/password/reset',
    'GET /api/customer/designs', 'PUT /api/customer/designs/{id}', 'POST /api/customer/designs/{id}/submit-showcase',
    'GET /api/customer/orders', 'POST /api/customer/orders', 'GET /api/customer/orders/{id}', 'POST /api/customer/orders/{id}/accept',
    'GET /api/admin/orders', 'GET /api/admin/orders/{id}', 'PATCH /api/admin/orders/{id}', 'PATCH /api/admin/orders/{id}/confirm', 'POST /api/admin/orders/{id}/advance',
    'GET /api/customer/messages', 'POST /api/customer/messages', 'GET /api/admin/messages', 'POST /api/admin/messages',
    'GET /api/customer/orders/{id}/billing', 'GET /api/admin/orders/{id}/billing', 'POST /api/admin/orders/{id}/invoice', 'PATCH /api/admin/invoices/{id}/mark-paid',
    'GET /api/customer/delivery/{orderId}', 'POST /api/admin/delivery', 'PATCH /api/admin/delivery/{id}/status',
    'GET /api/admin/orders/{id}/production', 'POST /api/admin/output-logs',
    'GET /api/admin/ai/recommendation-metrics', 'GET /api/admin/orders/{id}/ai-context',
];

function methodSource(string $action): ?string
{
    [$class, $method] = str_contains($action, '@') ? explode('@', $action) : [$action, '__invoke'];
    if (! method_exists($class, $method)) {
        return null;
    }
    $ref = new ReflectionMethod($class, $method);
    $lines = file($ref->getFileName());

    return implode('', array_slice($lines, $ref->getStartLine() - 1, $ref->getEndLine() - $ref->getStartLine() + 1));
}

// Top-level keys of the array literal after the first (or last) $anchor; the last json() is usually the success path.
function keysAfter(string $src, string $anchor, bool $last = false): array
{
    $pos = $last ? strrpos($src, $anchor) : strpos($src, $anchor);
    if ($pos === false) {
        return [];
    }
    $depth = 0;
    $body = '';
    for ($i = $pos + strlen($anchor); $i < strlen($src); $i++) {
        $c = $src[$i];
        $depth += ($c === '[') - ($c === ']');
        if ($depth === 0) {
            break;
        }
        $body .= $depth === 1 ? $c : ' ';
    }
    preg_match_all("/'([\w.*]+)'\s*=>/", $body, $m);

    return array_values(array_unique($m[1]));
}

function responseFields(string $src): string
{
    if ($keys = keysAfter($src, 'response()->json(', true)) {
        return implode(', ', $keys);
    }
    if (preg_match('/->paginate\(/', $src)) {
        return 'Laravel paginator: data[], current_page, last_page, per_page, total, links';
    }

    return 'not parsed (returns a variable; read the controller)';
}

$routes = collect(Illuminate\Support\Facades\Route::getRoutes()->getRoutes())
    ->filter(fn ($r) => str_starts_with($r->uri(), 'api/'))
    ->sortBy(fn ($r) => $r->uri())
    ->values();

$out = ["# VFRB API\n", 'Generated by `php scripts/api-docs.php`. Do not edit by hand.', ''];
$out[] = "## Conventions\n";
$out[] = '- Errors: `{ "message": string, "errors"?: { field: [string] } }`. `errors` appears on 422 only.';
$out[] = '- Lists: the Laravel paginator shape, `{ data: [], current_page, last_page, per_page, total, links, ... }`.';
$out[] = '- Auth: Sanctum bearer token unless the route says `public`.'."\n";
$out[] = "## Core endpoints\n";

foreach ($routes as $r) {
    $verb = implode('|', array_diff($r->methods(), ['HEAD']));
    if (! in_array("{$verb} /{$r->uri()}", CORE) || ! ($src = methodSource($r->getActionName()))) {
        continue;
    }
    $req = keysAfter($src, 'validate(');
    $out[] = "### {$verb} /{$r->uri()}\n";
    $out[] = '- Request: '.($req ? implode(', ', $req) : 'none');
    $out[] = '- Response: '.responseFields($src)."\n";
}

$out[] = "## All routes ({$routes->count()})\n";
$out[] = '| Method | URI | Action | Middleware |';
$out[] = '|---|---|---|---|';
foreach ($routes as $r) {
    $mw = implode(', ', array_filter($r->gatherMiddleware(), fn ($m) => $m !== 'api')) ?: 'public';
    $out[] = sprintf('| %s | /%s | %s | %s |', implode(', ', array_diff($r->methods(), ['HEAD'])), // a bare | would split the table cell
        $r->uri(), str_replace('App\\Http\\Controllers\\', '', $r->getActionName()), $mw);
}

file_put_contents(__DIR__.'/../docs/API.md', implode("\n", $out)."\n");
echo 'docs/API.md written: '.$routes->count()." routes\n";
